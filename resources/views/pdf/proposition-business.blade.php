<h2>1. Business Plan — Proposition de valeur</h2>
<p><strong>Marché cible :</strong> ateliers de carrosserie/peinture en zone UEMOA/CEMAC (Mali, Sénégal, Côte d'Ivoire, Burkina Faso, etc.). Digitalisation des PME avec paiements Mobile Money et espèces.</p>
<p><strong>Proposition de valeur :</strong></p>
<ul>
    <li>Inspection carrosserie 360° (4 angles + zones choquées + code teinte) pour éviter les litiges.</li>
    <li>Suivi atelier par étapes : Tôlerie → Préparation → Cabine peinture → Mécanique rapide → Finition → Livraison.</li>
    <li>Gestion des consommables peinture au gramme/millilitre avec fiche de formulation de teinte.</li>
    <li>Dossiers sinistres & assurances (double payeur : part assurance + franchise client).</li>
    <li>Multi-devises (XOF/XAF/EUR/USD) et paiements locaux (Orange Money, Wave, Moov, espèces, virement).</li>
    <li>Notifications automatiques WhatsApp/SMS.</li>
    <li>Mobile-first pour utilisation sur parking et en atelier.</li>
</ul>

<h3>Modèle commercial : Hybride</h3>
<p>Licence on-premise (paiement unique) + abonnement annuel (maintenance, mises à jour, support). L'hébergement VPS Hetzner est inclus dans chaque offre. Ce modèle offre un coût prévisible pour le client et un revenu récurrent pour le prestataire.</p>

