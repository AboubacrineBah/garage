    <li>Améliorer la fidélisation client (notifications WhatsApp/SMS).</li>
</ul>
<p><strong>ROI estimé : 2 à 3 mois.</strong></p>

<h2>5. Sécurité — Priorité absolue</h2>
<ul>
    <li>Firewall Hetzner + UFW + Fail2Ban, SSH par clé.</li>
    <li>HTTPS (Let's Encrypt), CSRF, XSS, SQL injection, RBAC, rate limiting.</li>
    <li>Sauvegardes chiffrées quotidiennes, isolation par atelier, audit logs.</li>
    <li>Mots de passe Bcrypt, changement obligatoire au premier login.</li>
</ul>

