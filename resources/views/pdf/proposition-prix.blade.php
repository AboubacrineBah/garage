<h2>1. Présentation de l'application</h2>
<p><strong>Garage Moderne</strong> est une application web responsive (mobile-first) qui digitalise l'ensemble de la gestion de votre atelier de tôlerie, peinture et mécanique rapide. Conçue pour le marché ouest-africain (UEMOA/CEMAC), elle s'adapte aux réalités locales : paiements Mobile Money, multi-devises, notifications WhatsApp/SMS.</p>

<h3>Fonctionnalités incluses</h3>
<ul>
    <li><strong>Tableau de bord</strong> : KPI (ordres en cours, CA du jour, stock critique, crédits clients), graphiques.</li>
    <li><strong>Réception 360°</strong> : inspection photographique obligatoire (4 angles + zones choquées + code teinte).</li>
    <li><strong>Ordres de réparation</strong> : création rapide, suivi par étapes (tôlerie, préparation, cabine peinture, mécanique, finition, livraison).</li>
    <li><strong>Facturation multi-devises</strong> : XOF/XAF/EUR/USD, acomptes, modes de paiement locaux (espèces, Orange Money, Wave, Moov, virement).</li>
    <li><strong>Assurances / sinistres</strong> : gestion du double payeur (part assurance + franchise client).</li>
    <li><strong>Stock pièces</strong> : alertes stock critique, mouvements (entrée/sortie/ajustement), historique.</li>
    <li><strong>Laboratoire peinture</strong> : suivi des consommables au gramme/millilitre, fiche de formulation de teinte.</li>
    <li><strong>Clients & véhicules</strong> : fiches clients, historique véhicules, crédits.</li>
    <li><strong>Notifications</strong> : WhatsApp/SMS automatiques (devis prêt, véhicule terminé, rappels).</li>
    <li><strong>PDF</strong> : devis et facture téléchargeables.</li>
    <li><strong>Paramètres atelier</strong> : nom, adresse, templates de messages.</li>
    <li><strong>PWA</strong> : installable sur smartphone, mode hors-ligne partiel.</li>
</ul>

